"""Synthetic DEMO dataset generator.

Draws fake metal-like surfaces with simple scratch / crack / dent / colour-patch defects so the whole
pipeline can run without a real dataset. These images are NOT real industrial data.
"""
from pathlib import Path
import numpy as np
from PIL import Image, ImageDraw

STYLES = ["scratch", "crack", "dent", "color_defect"]
DEMO_MARKER = ".demo_dataset"


def _base(rng, s):
    img = np.full((s, s, 3), rng.uniform(0.45, 0.65))
    xs = np.linspace(0, 1, s)
    img += (rng.uniform(-0.1, 0.1) * xs[None, :] + rng.uniform(-0.1, 0.1) * xs[:, None])[..., None]
    img += rng.normal(0, 0.03, (s, s, 1))
    return img


def _blob(s, cx, cy, r):
    yy, xx = np.mgrid[0:s, 0:s]
    return np.exp(-(((xx - cx) ** 2 + (yy - cy) ** 2) / (2 * r ** 2)))


def _make(style, rng, s=96):
    img = _base(rng, s)
    if style == "dent":
        cx, cy, r = rng.uniform(25, s - 25), rng.uniform(25, s - 25), rng.uniform(9, 16)
        shade = _blob(s, cx, cy, r)
        light = _blob(s, cx - r * 0.6, cy - r * 0.6, r * 0.8) - _blob(s, cx + r * 0.6, cy + r * 0.6, r * 0.8)
        img += (0.22 * light + 0.0 * shade)[..., None]
    elif style == "color_defect":
        cx, cy, r = rng.uniform(20, s - 20), rng.uniform(20, s - 20), rng.uniform(8, 16)
        colour = np.array([rng.uniform(0.6, 1.0), rng.uniform(0, 0.4), rng.uniform(0, 0.4)])
        colour = colour[rng.permutation(3)]
        m = np.clip(_blob(s, cx, cy, r) * 1.6, 0, 1)[..., None] * 0.7
        img = img * (1 - m) + colour * m
    pil = Image.fromarray((np.clip(img, 0, 1) * 255).astype(np.uint8))
    d = ImageDraw.Draw(pil)
    if style == "scratch":
        for _ in range(int(rng.integers(1, 4))):
            x0, y0 = rng.uniform(0, s), rng.uniform(0, s)
            ang, ln = rng.uniform(0, np.pi), rng.uniform(40, 90)
            x1, y1 = x0 + ln * np.cos(ang), y0 + ln * np.sin(ang)
            c = int(rng.choice([235, 40]))
            d.line([(x0, y0), (x1, y1)], fill=(c, c, c), width=int(rng.integers(1, 3)))
    elif style == "crack":
        x, y = rng.uniform(10, s - 10), rng.uniform(10, s - 10)
        ang = rng.uniform(0, 2 * np.pi)
        pts = [(x, y)]
        for _ in range(int(rng.integers(8, 14))):
            ang += rng.normal(0, 0.8)
            x, y = x + 7 * np.cos(ang), y + 7 * np.sin(ang)
            pts.append((x, y))
        d.line(pts, fill=(25, 25, 25), width=int(rng.integers(1, 3)))
    for _ in range(int(rng.integers(0, 4))):  # random harmless specks (distractors)
        px, py = rng.uniform(0, s), rng.uniform(0, s)
        d.point((px, py), fill=(90, 90, 90))
    return pil


def style_for(name, idx):
    low = name.lower()
    for st in STYLES:
        if st.split("_")[0] in low:
            return st
    return STYLES[idx % len(STYLES)]


def generate_demo_dataset(raw_dir, classes, images_per_class=120, seed=42, size=96):
    raw_dir = Path(raw_dir)
    rng = np.random.default_rng(seed)
    for i, c in enumerate(classes):
        out = raw_dir / c
        out.mkdir(parents=True, exist_ok=True)
        style = style_for(c, i)
        for k in range(images_per_class):
            _make(style, rng, size).save(out / f"{c}_{k:04d}.png")
    (raw_dir / DEMO_MARKER).write_text("Synthetic demo images generated by this project. Not real data.\n")
    return raw_dir
